#!/usr/bin/env python3
"""Render benchmark CSV summaries as LaTeX tables included by the paper."""
from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd


DISPLAY_NAMES = {
    "ag_news": "AG News",
    "banking77": "Banking77",
    "emotion": "Emotion",
    "financial_phrasebank": "Financial PhraseBank",
    "rotten_tomatoes": "Rotten Tomatoes",
    "sst2": "SST-2",
    "trec": "TREC",
    "tweet_eval_sentiment": "TweetEval Sentiment",
    "twenty_newsgroups": "20 Newsgroups",
    "yelp_polarity": "Yelp Polarity",
}
STRATEGY_NAMES = {
    "random": "Random",
    "uncertainty_al": "Uncertainty AL",
    "diversity_al": "Diversity AL",
    "hybrid_al": "Hybrid AL",
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--summary", default="results/paper_core_summary.csv")
    parser.add_argument("--recommendations", default="results/budget_recommendations.csv")
    parser.add_argument("--output-tex", default="paper/generated_results_tables.tex")
    return parser.parse_args()


def _escape(value: object) -> str:
    return str(value).replace("_", "\\_")


def render_tables(summary: pd.DataFrame, recommendations: pd.DataFrame) -> str:
    lines = [
        "% Generated by scripts/make_paper_latex_tables.py; do not edit by hand.",
        "\\begin{table}[H]",
        "\\centering",
        "\\caption{Best strategy-budget point per dataset under the base cost scenario. Scores are mean macro F1 with 95\\% confidence intervals over five strategy-selection seeds.}",
        "\\label{tab:benchmark-results}",
        "\\small",
        "\\begin{tabular}{llrrr}",
        "\\toprule",
        "Dataset & Best strategy & Macro F1 (95\\% CI) & Budget & Base cost \\\\",
        "\\midrule",
    ]
    for row in summary.itertuples(index=False):
        lines.append(
            f"{DISPLAY_NAMES.get(row.dataset, _escape(row.dataset))} & "
            f"{STRATEGY_NAMES.get(row.best_strategy, _escape(row.best_strategy))} & "
            f"{row.mean_macro_f1:.3f} [{row.ci_lower_95:.3f}, {row.ci_upper_95:.3f}] & "
            f"{int(row.best_budget)} & \\${row.mean_total_cost:.2f} \\\\"
        )
    lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{table}", ""])

    selected = recommendations[recommendations["target_f1"].isin([0.5, 0.75, 0.8])]
    lines.extend(
        [
            "\\begin{table}[H]",
            "\\centering",
            "\\caption{Minimum-cost strategy and budget for representative target macro-F1 levels under the base cost scenario. A dash indicates that the target was not reached in the reported budget grid.}",
            "\\label{tab:budget-recommendations}",
            "\\scriptsize",
            "\\begin{tabular}{lrrll}",
            "\\toprule",
            "Dataset & Target & Budget & Strategy & Estimated cost \\\\",
            "\\midrule",
        ]
    )
    for row in selected.itertuples(index=False):
        reached = pd.notna(row.required_budget) and str(row.required_budget) != ""
        budget = str(int(float(row.required_budget))) if reached else "--"
        strategy = STRATEGY_NAMES.get(str(row.cheapest_strategy), "--") if reached else "--"
        cost = f"\\${float(row.estimated_cost):.2f}" if reached else "--"
        lines.append(
            f"{DISPLAY_NAMES.get(row.dataset, _escape(row.dataset))} & {float(row.target_f1):.2f} & "
            f"{budget} & {strategy} & {cost} \\\\"
        )
    lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{table}", ""])
    return "\n".join(lines)


def main() -> None:
    args = parse_args()
    output = Path(args.output_tex)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        render_tables(pd.read_csv(args.summary), pd.read_csv(args.recommendations)),
        encoding="utf-8",
    )
    print(f"Wrote generated LaTeX tables to {output}")


if __name__ == "__main__":
    main()
